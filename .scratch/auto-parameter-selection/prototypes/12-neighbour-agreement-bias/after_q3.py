"""Throwaway: the ticket 06 selection table again, with identical-graph links left out of the NA mean (ticket 12, Q3).

    .venv/Scripts/python.exe .scratch/auto-parameter-selection/prototypes/12-neighbour-agreement-bias/after_q3.py \
        --runs <scratchpad>/runs05/parallel --out .scratch/auto-parameter-selection/prototypes/12-neighbour-agreement-bias
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

DATASETS = ("overall", "puzzle", "rpg", "simulation", "strategy")
BANDS = ((3, 6), (7, 10), (11, 14), (15, 20))


def renormalise(records, links):
    """NA as decided in ticket 12: mean ARI over comparable links whose graphs differ."""
    for r in records.values():
        k = (r["g"], r["s"])
        mine = [x for x in links if tuple(x["p"]) == k or tuple(x["q"]) == k]
        ok = [x for x in mine if x["status"] == "ok" and not x["identical_graph"]]
        if r["selected"] is None:
            r["na12"] = (None, "no_selected_partition", 0, 0)
        elif not ok:
            r["na12"] = (None, "no_comparable_neighbours", 0, sum(x["identical_graph"] for x in mine))
        else:
            r["na12"] = (statistics.fmean(x["ari"] for x in ok), "ok", len(ok),
                         sum(x["identical_graph"] and x["status"] == "ok" for x in mine))


def qualifies(r) -> bool:
    na, status, n, _ = r["na12"]
    return (status == "ok" and r["retention"] >= 0.50 and r["isolated_share"] <= 0.10
            and r["lcc_share_non_isolated"] >= 0.90 and n >= 2)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    rows = ["# Selection with identical-graph links left out of Neighbour Agreement", "",
            "Default constraints, tolerance 0.05, ticket 05 records. Generated by `after_q3.py`.", "",
            "| Dataset | NA changed | NA lost | Qualifying | Max NA (at g,s) | Near-best set | **Chosen** | NA (over n) "
            "| identical links dropped | Multi-Tag Clusters | Tags | Retention | Selected / Workbench γ | Seed-Noise Floor | Hits |",
            "|---|---:|---:|---:|---|---:|---|---|---:|---:|---:|---:|---|---:|---:|"]
    bands = ["", "Mean NA by g band (pairs with NA):", "", "| Dataset | " + " | ".join(f"g {a}–{b}" for a, b in BANDS) + " |",
             "|---|" + "---:|" * len(BANDS)]
    for ds in DATASETS:
        doc = json.loads((Path(args.runs) / f"{ds}.json").read_text(encoding="utf-8"))
        records = {(r["g"], r["s"]): r for r in doc["records"]}
        renormalise(records, doc["links"])
        changed = sum(r["na12"][0] is not None and r["neighbour_agreement"]["mean"] is not None
                      and abs(r["na12"][0] - r["neighbour_agreement"]["mean"]) > 1e-12 for r in records.values())
        lost = sum(r["na12"][0] is None and r["neighbour_agreement"]["mean"] is not None for r in records.values())
        q = {k: r for k, r in records.items() if qualifies(r)}
        top = max(r["na12"][0] for r in q.values())
        at = [k for k, r in q.items() if abs(r["na12"][0] - top) <= 1e-12]
        near = sorted(k for k, r in q.items() if r["na12"][0] >= top - 0.05 - 1e-12)
        k = near[0]
        r, sel = records[k], records[k]["selected"]
        rows.append(f"| {ds} | {changed} | {lost} | {len(q)} | {top:.3f} ({'; '.join(f'{g},{s}' for g, s in at)}) | {len(near)} "
                    f"| **g={k[0]}, s={k[1]}** | {r['na12'][0]:.3f} (n={r['na12'][2]}) | {r['na12'][3]} | {sel['n_multi']} "
                    f"| {r['n_tags']} | {r['retention']:.3f} | {sel['selected_resolution']:.3f} / {sel['workbench_resolution']} "
                    f"| {sel['seed_noise_floor']:.2f} | {sel['hits']} |")
        cells = []
        for a, b in BANDS:
            v = [r["na12"][0] for r in records.values() if a <= r["g"] <= b and r["na12"][0] is not None]
            cells.append(f"{statistics.fmean(v):.3f}")
        bands.append(f"| {ds} | " + " | ".join(cells) + " |")
    Path(args.out, "after-q3.md").write_text("\n".join(rows + bands) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
